# ---------------------------------------------------------------------------
# Hoffman2 SGE array job: controlled-strength study, single- and multi-factor
# (python/sim_run_controlled_study.py; docs/viper_shared_extensions_design.md).
#
# Tasks (python python/sim_run_controlled_study.py --list):
#    1-42   single-factor grid, n {100,200,500} x P {600,3000} x 7 c, reps 1-10
#   43-54   single-factor P = 10000 x c {0.3,1,3,10} x n, reps 1-3
#   55-216  two-factor study (one strong, one weak relevant factor): the same (n, P, c)
#           cells x omega_2 {0.25, 0.5, 0.75} = 162 cells, reps 1-10 (data generated by
#           the task); the P = 10000 cells take ~3-4 h (10 reps)
#  217-270  single-factor grid on rescaled data (g_true == g_target; m = 1 design of
#           generate_multifactor_data.R --single, data generated by the task): the 54
#           (n, P, c) cells, reps 1-10, with per-factor diagnostics for factor-selection
#           rules (python/factor_selection_diag.py: + 1 permuted-y and 2 subsample VIPER
#           fits per replicate only with --extra-fits; off by default)
#           Submit only these:  qsub -t 217-270 cluster/submit_controlled_study.sh
# Each task runs all replicates of one cell: VIPER (package defaults, incl. the new
# local-inference defaults), local inference with recorded trajectory, MOFA2, PCA,
# ridge, elastic net. Output: sim/results/controlled_study/<arm>/scores/<cell>.csv
# (resumable: resubmitting a task skips finished replicates).
#
# Time: ~4 min per replicate at P = 600, ~5-8 min at P = 3000, ~20 min at P = 10000
# (VIPER ~10 min + local + elastic net), so tasks take ~0.7-1.5 h; 16 h is headroom.
#
# Needs on the cluster: the repo, conda env "multiomic", R with MOFA2, and the
# single-factor data sim/data/multi_view_shared_controlled/k.5 (copy it over; ~3 GB).
# Submit from the repo root:   qsub cluster/submit_controlled_study.sh
# After copying the results back:  python python/sim_run_controlled_study.py --compare
# ---------------------------------------------------------------------------

echo "=== Task $SGE_TASK_ID starting on $(hostname) at $(date) ==="
export OMP_NUM_THREADS=2
export MKL_NUM_THREADS=2
source /u/local/apps/miniconda3/latest/etc/profile.d/conda.sh
conda activate multiomic
module load R/4.4.0

python python/sim_run_controlled_study.py --task-id "$SGE_TASK_ID"

echo "=== Task $SGE_TASK_ID finished at $(date) ==="
