"""
Right-censored survival study, log-normal AFT (docs/viper_shared_extensions_design.md §4),
for the Hoffman2 cluster (cluster/submit_survival.sh) or locally.

Data: R/generate_survival_data.R -> sim/data/multi_view_shared_survival/ (generated by the
task if missing). 336 conditions = 24 base cells (n {100, 200, 500} x P {600, 3000} x
c {0.6, 1, 3, 10}) x 14 scenario levels (S1 log-normal random censoring 0 / 0.3 / 0.6 /
0.8; S2 random + administrative 0.3 / 0.6; S3 Weibull and log-logistic truths 0.3 / 0.6;
S4 censoring depending on view 1 0.3 / 0.6; S5 two relevant factors 0.3 / 0.6), 10 reps.

VIPER uses the package defaults throughout (run_methods.with_defaults, empty train_config):
MGP, k = 15, pyro seed = rep, and the package local-inference defaults.

Methods (one row each per dataset):
  viper_lognormal        VIPER-Shared, outcome="lognormal_aft"; closed-form test scores
  viper_lognormal_local  the same fit, local-inference test scores
  viper_gauss_naive      Gaussian VIPER on log y, censoring ignored
  viper_gauss_events     Gaussian VIPER on log y of the events only
  pca5_aft, pca15_aft    PCA scores + log-normal AFT (censored-normal MLE)
  mofa_aft               MOFA2 (15 factors) scores + log-normal AFT
  pca5_cox, mofa_cox     scores + Cox PH (survival metrics only)
  coxnet                 elastic-net Cox on the stacked views, CV penalty (survival metrics only)
  oracle                 population best linear predictor of log T from x (b*), and
  oracle_known_z         beta_0 + z' beta (the true linear predictor)

Metrics:
  primary    mse_logT: test MSE on the true log T, divided by Var(log T) = 1.5 (the
             population variance, so values line up with the standardised Gaussian grids);
             R_star_rel = R* / 1.5 for reference
  diagnostic risk_rel: exact excess risk (R - R*) / R* of the linear predictor of log T
  survival   uno_c, harrell_c, ibs, mean_auc (survival_metrics), on the censored test data
  other      calib_slope (regression of true log T on the prediction), cov95 / width95 of
             log T (methods with a predictive sd), kappa2 per relevant factor (factor
             methods), VIPER stop epoch / fit time / local epochs and time, runtimes
  runtime    time to get the method's predictions from the training data: for every
             VIPER row the training fit (fit_time) plus, for viper_lognormal_local, local
             inference (local_time); MOFA rows include the MOFA fit

Output: sim/results/survival_study/scores/<cond>.csv (one file per condition; resumable
by rep), models/, mofa/.

usage (from python/):
  python sim_run_survival.py --list
  OMP_NUM_THREADS=2 python sim_run_survival.py --task-id 5 [--reps 1]
"""
import argparse, os, subprocess, sys, time, warnings
import numpy as np, pandas as pd
sys.path.insert(1, os.path.dirname(os.path.abspath(__file__)))
warnings.filterwarnings("ignore")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "sim", "data", "multi_view_shared_survival")
OUT = os.path.join(ROOT, "sim", "results", "survival_study")
K_FIT = 15
REPS = tuple(range(1, 11))
VAR_LOGT = 1.5        # signal 1 + sigma_y^2 0.5 (every error distribution has variance 1)

SCEN = ([("S1", "normal", "random", r) for r in (0, 0.3, 0.6, 0.8)]
        + [("S2", "normal", "admin", r) for r in (0.3, 0.6)]
        + [("S3", e, "random", r) for e in ("gumbel", "logistic") for r in (0.3, 0.6)]
        + [("S4", "normal", "covariate", r) for r in (0.3, 0.6)]
        + [("S5", "normal", "random", r) for r in (0.3, 0.6)])


def cond_name(scen, n, P, c, error, cens, rate):
    return f"{scen}_n{n}_P{P}_c{c:g}_{error}_{cens}{rate:g}"


def tasks():
    return [cond_name(s, n, P, c, e, cz, r) for n in (100, 200, 500) for P in (600, 3000)
            for c in (0.6, 1, 3, 10) for s, e, cz, r in SCEN]


def load(cond, rep):
    from run_methods import load_rds
    f = f"sim_data_surv_{cond}_rep{rep}.rds"
    return load_rds(os.path.join(DATA, "train", cond, f)), load_rds(os.path.join(DATA, "test", cond, f))


def generate(cond, reps):
    subprocess.run(["Rscript", os.path.join(ROOT, "R", "generate_survival_data.R"),
                    "--only", cond, "--reps", ",".join(map(str, reps))], check=True, stdout=subprocess.DEVNULL)


def _np(x):
    return np.asarray(x.detach().cpu().double().numpy() if hasattr(x, "detach") else x, dtype=float).reshape(-1)


def fit_viper(sub, model_config, rep, stem):
    import pyro
    from run_methods import train_model
    pyro.clear_param_store(); pyro.set_rng_seed(rep)
    t0 = time.time()
    model, h, _ = train_model({"k": K_FIT, "dense_model": False, **model_config}, {}, sub, None,
                              model_type="shared", write=False)
    fit_time = time.time() - t0
    pyro.get_param_store().save(stem + "_paramstore.pth")
    return model, fit_time


def one(cond, rep):
    os.environ.setdefault("OMP_NUM_THREADS", "2")
    import torch, pyro
    torch.set_num_threads(int(os.environ["OMP_NUM_THREADS"]))
    import multiview_shared  # noqa: F401
    from run_methods import process_data, train_model_locally
    from viper_predict import load_guide_moments, closed_form_scores
    from controlled_scoring import fit_mofa
    from sklearn.decomposition import PCA
    from constants import Params
    import risk_metrics as rm
    import survival_metrics as sm

    for d in ("models", "mofa", "scores"):
        os.makedirs(os.path.join(OUT, d), exist_ok=True)
    tr, te = load(cond, rep)
    sub, tsub, dp = process_data(tr, te, model_type="shared", outcome="lognormal_aft")
    L = dp["L"]; n = int(dp["train_X_l_list_clean"][0].shape[0])
    ym, ysd = float(dp["y_mean"]), float(dp["y_sd"])
    t_tr, e_tr = _np(tr["y"]), _np(tr["event"]).astype(int)
    t_te, e_te = _np(te["y"]), _np(te["event"]).astype(int)
    logT_te, beta0 = _np(te["logT"]), float(_np(tr["beta0"])[0])
    times = sm.eval_times(t_tr, t_te, e_te)
    X_tr = [x.double() for x in dp["train_X_l_list_clean"]]; X_te = [x.double() for x in dp["test_X_l_list_clean"]]
    Xc_tr, Xc_te = torch.cat(X_tr, 1).numpy(), torch.cat(X_te, 1).numpy()
    sizes = [x.shape[1] for x in X_tr]
    split = lambda A: list(torch.split(torch.as_tensor(np.asarray(A), dtype=torch.float64), sizes))

    theta = rm.true_params(tr); orc = rm.oracle(theta)
    rel = [k for k in range(theta["beta"].numel()) if float(theta["beta"][k]) != 0]
    k_strong, k_weak = rel[0], rel[-1]
    g_true = np.atleast_1d(_np(tr["g_true"]))
    scen, _, _, c_s, err, cz = cond.split("_")
    key = {"cond": cond, "scen": scen, "n": n, "P_grid": int(sum(_np(tr["p_l"]))), "c": float(c_s[1:]),
           "error": err, "cens": cz.rstrip("0123456789."), "cens_rate": float(cz.lstrip("abcdefghijklmnopqrstuvwxyz")),
           "rep": rep, "cens_train": 1 - e_tr.mean(), "cens_test": 1 - e_te.mean(), "n_events": int(e_tr.sum()),
           "g_true": float(g_true[-1]), "g_true_strong": float(g_true[0]) if g_true.size > 1 else np.nan,
           "R_star_rel": float(orc["R_star"]) / VAR_LOGT}
    rows = []

    def add(method, m_raw=None, s_raw=None, risk=None, surv=None, coef=None, runtime=None, load_s=None, extra=None):
        """m_raw / s_raw: predictive mean / sd of log T (raw scale); risk: higher = shorter survival."""
        r = {**key, "method": method, "runtime": runtime}
        if m_raw is not None:
            m_raw = np.asarray(m_raw, float)
            r["mse_logT"] = float(np.mean((m_raw - logT_te) ** 2)) / VAR_LOGT
            r["calib_slope"] = float(np.polyfit(m_raw, logT_te, 1)[0])
            risk = -m_raw if risk is None else risk
            if s_raw is not None:
                s_raw = np.broadcast_to(np.asarray(s_raw, float), m_raw.shape)
                lo, hi = m_raw - 1.96 * s_raw, m_raw + 1.96 * s_raw
                r["cov95"] = float(np.mean((logT_te >= lo) & (logT_te <= hi))); r["width95"] = float(np.mean(hi - lo))
                if surv is None and len(times) >= 2:
                    surv = sm.aft_survival(m_raw, s_raw, times)
        if coef is not None:                       # (b_raw list, c_raw) of a linear predictor of log T
            b, c0 = coef
            er = rm.exact_risk(b, c0 - beta0, theta, orc)
            r["risk_rel"] = float(er["risk_rel"])
        if risk is not None:
            r.update(sm.survival_scores(t_tr, e_tr, t_te, e_te, risk, surv, times))
        if load_s is not None:
            k2 = rm.kappa2_hat(rm.raw_loadings(load_s, dp), theta)["kappa2_k"]
            r.update(kappa2_strong=float(k2[k_strong]), kappa2_weak=float(k2[k_weak]), kappa2_rel_mean=float(k2[rel].mean()))
        r.update(extra or {})
        rows.append(r)

    # Oracles
    Xraw_te = torch.cat([x.double() for x in te["X_l"]], 1)
    b_star = torch.cat([b.reshape(-1) for b in orc["b_star"]]) if isinstance(orc["b_star"], (list, tuple)) else orc["b_star"]
    add("oracle", m_raw=beta0 + (Xraw_te @ b_star.double()).numpy(), s_raw=float(orc["R_star"]) ** 0.5)
    add("oracle_known_z", m_raw=beta0 + (te["Z"].double() @ theta["beta"]).numpy(), s_raw=float(theta["sigma2_y"]) ** 0.5)

    # VIPER log-normal AFT
    stem = os.path.join(OUT, "models", f"lognormal_{cond}_rep{rep}")
    model, fit_time = fit_viper(sub, {"outcome": "lognormal_aft"}, rep, stem)
    stop = model.total_epochs
    mom = load_guide_moments(stem + "_paramstore.pth", L)
    cf = closed_form_scores(mom, X_te)
    b_raw, c_raw = rm.to_raw_scale(cf["coef"], dp, ym, ysd, float(mom["m_intercept"]))
    add("viper_lognormal", m_raw=ym + ysd * cf["yhat"].numpy(), s_raw=ysd * cf["pred_var"].sqrt().numpy(),
        coef=(b_raw, c_raw), runtime=fit_time, load_s=mom["M"],
        extra={"stop_epoch": stop, "fit_time": fit_time,
               "sigma_y_hat": ysd * float(mom["E_sigma2_y"]) ** 0.5, "intercept_hat": ym + ysd * float(mom["m_intercept"])})
    # local inference (package local defaults)
    pyro.clear_param_store(); pyro.get_param_store().load(stem + "_paramstore.pth"); torch.manual_seed(rep)
    model, h_te, st = train_model_locally(model, {}, tsub, model_type="shared")
    ps = pyro.get_param_store()
    m_loc = ps[Params.loc_Z_pred].detach().double(); s_loc = ps[Params.scale_Z_pred].detach().double()
    mb, s2b = mom["m_beta"], mom["s2_beta"]
    mu = mom["m_intercept"] + m_loc @ mb
    var = mom["E_sigma2_y"] + mom["s2_intercept"] + (s_loc ** 2 * (mb ** 2 + s2b)).sum(1) + (m_loc ** 2 * s2b).sum(1)
    add("viper_lognormal_local", m_raw=ym + ysd * mu.numpy(), s_raw=ysd * var.sqrt().numpy(),
        runtime=fit_time + float(st["inference_time"]), load_s=mom["M"],      # fit + local inference
        extra={"stop_epoch": stop, "fit_time": fit_time,
               "local_epochs": model.local_epochs, "local_time": float(st["inference_time"])})
    pyro.clear_param_store()

    # Gaussian VIPER on log y: censoring ignored, and events only
    log_tr, log_te = torch.log(tr["y"].double()), torch.log(te["y"].double())
    for label, keep in (("viper_gauss_naive", np.ones(n, bool)), ("viper_gauss_events", e_tr == 1)):
        kt = torch.as_tensor(keep)
        d_tr = {"X_l": [x[kt] for x in tr["X_l"]], "y": log_tr[kt].to(tr["y"].dtype), "K": tr["K"], "Z": None}
        d_te = {"X_l": te["X_l"], "y": log_te.to(te["y"].dtype), "K": te["K"], "Z": None}
        sub_g, _, dp_g = process_data(d_tr, d_te, model_type="shared")
        stem_g = os.path.join(OUT, "models", f"{label}_{cond}_rep{rep}")
        model_g, ft = fit_viper(sub_g, {}, rep, stem_g)
        mom_g = load_guide_moments(stem_g + "_paramstore.pth", L)
        cf_g = closed_form_scores(mom_g, [x.double() for x in dp_g["test_X_l_list_clean"]])
        ymg, ysg = float(log_tr[kt].mean()), float(log_tr[kt].std())
        bg, cg = rm.to_raw_scale(cf_g["coef"], dp_g, ymg, ysg)
        add(label, m_raw=ymg + ysg * cf_g["yhat"].numpy(), s_raw=ysg * cf_g["pred_var"].sqrt().numpy(),
            coef=(bg, cg), runtime=ft, load_s=None,
            extra={"stop_epoch": model_g.total_epochs, "fit_time": ft})
        pyro.clear_param_store()

    # PCA scores + log-normal AFT / Cox
    y_s = dp["train_y_clean"].double().numpy().reshape(-1)          # standardised log y
    for kc in (5, 15):
        t0 = time.time()
        pca = PCA(n_components=kc, random_state=0).fit(Xc_tr)
        T_tr, T_te = pca.transform(Xc_tr), pca.transform(Xc_te)
        coef, sig = sm.censored_normal_mle(np.c_[np.ones(n), T_tr], y_s, e_tr)
        V = pca.components_.T; bs = V @ coef[1:]; cs = coef[0] - pca.mean_ @ bs
        add(f"pca{kc}_aft", m_raw=ym + ysd * (cs + Xc_te @ bs), s_raw=ysd * sig,
            coef=rm.to_raw_scale(split(bs), dp, ym, ysd, cs), runtime=time.time() - t0, load_s=split(V))
        if kc == 5:
            t0 = time.time()
            cox = sm.cox_fit(T_tr, t_tr, e_tr)
            surv = np.vstack([f(times) for f in cox.predict_survival_function(T_te)]) if len(times) >= 2 else None
            add("pca5_cox", risk=cox.predict(T_te), surv=surv, runtime=time.time() - t0)

    # MOFA scores + log-normal AFT / Cox
    mofa_npz = os.path.join(OUT, "mofa", f"mofa_{cond}_rep{rep}.npz")
    if not os.path.exists(mofa_npz):
        fit_mofa(dp, mofa_npz)
    d = np.load(mofa_npz); Z, Zt = d["Z_train"], d["Z_test"]; W = [d[f"weights_view{l}"] for l in range(L)]
    t0 = time.time()
    coef, sig = sm.censored_normal_mle(np.c_[np.ones(n), Z], y_s, e_tr)
    Wc = np.vstack(W); bs = Wc @ np.linalg.solve(Wc.T @ Wc, coef[1:])
    add("mofa_aft", m_raw=ym + ysd * (coef[0] + Zt @ coef[1:]), s_raw=ysd * sig,
        coef=rm.to_raw_scale(split(bs), dp, ym, ysd, coef[0]), runtime=float(d["runtime"]) + time.time() - t0,
        load_s=[torch.as_tensor(w) for w in W])
    t0 = time.time()
    cox = sm.cox_fit(Z, t_tr, e_tr)
    surv = np.vstack([f(times) for f in cox.predict_survival_function(Zt)]) if len(times) >= 2 else None
    add("mofa_cox", risk=cox.predict(Zt), surv=surv, runtime=float(d["runtime"]) + time.time() - t0)   # MOFA fit + Cox

    # Elastic-net Cox on the stacked views
    t0 = time.time()
    try:
        cn, alpha = sm.coxnet_cv(Xc_tr, t_tr, e_tr, seed=rep)
        surv = (np.vstack([f(times) for f in cn.predict_survival_function(Xc_te, alpha=alpha)])
                if len(times) >= 2 else None)
        add("coxnet", risk=cn.predict(Xc_te, alpha=alpha), surv=surv, runtime=time.time() - t0,
            extra={"coxnet_alpha": alpha})
    except Exception as ex:                       # e.g. too few events to fit
        add("coxnet", runtime=time.time() - t0, extra={"fit_error": repr(ex)[:200]})
    return rows


def run_task(cond, reps):
    generate(cond, reps)
    out = os.path.join(OUT, "scores", f"{cond}.csv")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    done = set(pd.read_csv(out).rep) if os.path.exists(out) else set()
    for rep in reps:
        if rep in done:
            continue
        t0 = time.time()
        new = pd.DataFrame(one(cond, rep))
        if os.path.exists(out):
            new = pd.concat([pd.read_csv(out), new], ignore_index=True)
        new.to_csv(out, index=False)
        print(f"{cond} rep {rep}: {time.time() - t0:.0f}s", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--task-id", type=int, help="1-based task index (SGE_TASK_ID); see --list")
    ap.add_argument("--reps", nargs="*", type=int, default=None)
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    tl = tasks()
    if a.list:
        for i, c in enumerate(tl, 1):
            print(i, c)
        print(f"{len(tl)} tasks")
        return
    if a.task_id is None:
        ap.error("give --task-id N (see --list)")
    run_task(tl[a.task_id - 1], a.reps or REPS)


if __name__ == "__main__":
    main()
