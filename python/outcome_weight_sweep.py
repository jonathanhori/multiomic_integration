"""
Outcome-weight sweep for SupMultiviewShared across the misaligned scenarios.

For each (n, p_l) cell, alignment scenario and replicate, fits the model at
each outcome_weight x minibatch_fraction setting and records held-out outcome
MSE and training reconstruction error. outcome_weight is dimension-dependent,
so each cell uses the same recipe, labelled so results are comparable across p:

    "1x"       -> 1                  (original objective)
    "per-view" -> sum_l p_l / L
    "full"     -> sum_l p_l          (one outcome term per reconstruction term)

Data (generated by generate_data.Rmd, misaligned scenarios):
    sim/data/multi_view_shared_misaligned/k.5/{train,test}/
        n{n}p{p}_snr{x}.{y}_sparse{s}_align_{label}/sim_data_shared_rep{r}.rds

Results are appended to a CSV after every fit; rows already present are
skipped, so the script can be interrupted and resumed. Plots and summaries of
the CSV: sim/exploration/shared_outcome_weight.qmd.

usage:
    python outcome_weight_sweep.py [--reps 3] [--out PATH.csv] [--n-post 100]
"""
import argparse
import os
import sys
from pathlib import Path

import pandas as pd
import pyro
import torch

sys.path.insert(1, "/Users/jonathanhori/multiomic_integration/python")
from run_methods import (
    load_rds, process_data, train_model, train_model_locally, evaluate_fitted_model,
)

# ---------------------------------------------------------------------------
# Sweep configuration
# ---------------------------------------------------------------------------
DATA_ROOT = os.path.expanduser(
    "~/multiomic_integration/sim/data/multi_view_shared_misaligned/k.5")
DEFAULT_OUT = os.path.expanduser(
    "~/multiomic_integration/sim/results/integration_shared_misaligned/outcome_weight_sweep.csv")

CELLS        = [(100, 100), (500, 100), (500, 1000)]          # (n, p_l)
ALIGN_LABELS = ["symmetric", "mild_misalignment", "strong_misalignment", "anti_aligned"]
WEIGHT_KINDS = ["1x", "per-view", "full"]
FRACTIONS    = [0.2]                                           # minibatch_fraction grid
SNR_X, SNR_Y, SPARSITY = 2, 2, 0.25
K_DELTA = 10

TRAIN_CONFIG = {
    "eta":                   0.25,
    "delta":                 1e-16,
    "t":                     0.1,
    "num_particles":         1,
    "minibatch_fraction":    0.15,
    "min_epochs":            200,
    "max_epochs":            500,
    "convergence_criterion": "elbo_snr",
    "window":                50,
    "snr_threshold":         5,
}
DEVICE = torch.device("cpu")
KEY_COLS = ["n", "p_l", "align_label", "rep", "weight_kind", "minibatch_fraction"]


def load_cell(n, p_l, align_label, rep):
    """Load and process one misaligned condition into model-ready subsets."""
    cond = f"n{n}p{p_l}_snr{SNR_X}.{SNR_Y}_sparse{SPARSITY}_align_{align_label}"
    sim_data      = load_rds(f"{DATA_ROOT}/train/{cond}/sim_data_shared_rep{rep}.rds")
    sim_data_test = load_rds(f"{DATA_ROOT}/test/{cond}/sim_data_shared_rep{rep}.rds")
    train_subset, test_subset, data_package = process_data(
        sim_data, sim_data_test, training_split=False, training_size=0.8, seed=123,
        model_type="shared")
    return train_subset, test_subset, data_package, int(sim_data["K"])


def weight_grid(data_package):
    """outcome_weight for each WEIGHT_KINDS label, from this cell's dimensions."""
    views = data_package["train_X_l_list_clean"]
    total_p = sum(int(x.shape[1]) for x in views)
    return dict(zip(WEIGHT_KINDS, [1.0, float(total_p // len(views)), float(total_p)]))


def fit_and_evaluate(train_subset, test_subset, data_package, k_fit, outcome_weight,
                     minibatch_fraction, rep_config, n_post):
    pyro.clear_param_store()
    model_config = {"k": k_fit, "dense_model": False, "outcome_weight": outcome_weight}
    train_config = {**TRAIN_CONFIG, "minibatch_fraction": minibatch_fraction}

    factor_model, train_handler, global_state = train_model(
        model_config, train_config, train_subset,
        model_type="shared", write=False, device=DEVICE)
    # Local inference for test Z uses X only — outcome_weight does not enter.
    factor_model, test_handler, local_state = train_model_locally(
        factor_model, train_config, test_subset, model_type="shared", device=DEVICE)
    eval_table, _, _, _ = evaluate_fitted_model(
        rep_config, data_package, train_handler, test_handler,
        global_state, local_state, n_post, model_type="shared")
    return eval_table, factor_model.total_epochs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reps", type=int, default=3, help="replicates per (cell, scenario)")
    parser.add_argument("--n-post", type=int, default=100, help="posterior samples for evaluation")
    parser.add_argument("--out", default=DEFAULT_OUT, help="results CSV (resumed if it exists)")
    args = parser.parse_args()

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    if os.path.exists(args.out):
        results = pd.read_csv(args.out)
        done = set(map(tuple, results[KEY_COLS].values))
        print(f"Resuming: {len(results)} rows already done.")
    else:
        results = pd.DataFrame()
        done = set()

    for n, p_l in CELLS:
        for label in ALIGN_LABELS:
            for rep in range(1, args.reps + 1):
                todo = [(frac, kind) for frac in FRACTIONS for kind in WEIGHT_KINDS
                        if (n, p_l, label, rep, kind, frac) not in done]
                if not todo:
                    continue
                train_subset, test_subset, data_package, k_true = load_cell(n, p_l, label, rep)
                weights = weight_grid(data_package)
                rep_config = {"n": n, "p_l": p_l, "snr_x": SNR_X, "snr_y": SNR_Y,
                              "rep": rep, "sparsity": SPARSITY, "k_delta": K_DELTA}

                for frac, kind in todo:
                    eval_table, epochs = fit_and_evaluate(
                        train_subset, test_subset, data_package, k_true + K_DELTA,
                        weights[kind], frac, rep_config, args.n_post)
                    row = {
                        "n": n, "p_l": p_l, "align_label": label, "rep": rep,
                        "weight_kind": kind, "outcome_weight": weights[kind],
                        "minibatch_fraction": frac,
                        "outcome_mse":    float(eval_table["outcome_mse"].iloc[0]),
                        "mean_joint_rse": float(eval_table["joint_rse"].mean()),
                        "mean_test_rse":  float(eval_table["test_rse"].mean()),
                        "global_epochs":  int(epochs),
                    }
                    results = pd.concat([results, pd.DataFrame([row])], ignore_index=True)
                    results.to_csv(args.out, index=False)
                    print(f"n={n} p={p_l} {label:<20} rep{rep} {kind:<8} frac={frac} "
                          f"-> mse={row['outcome_mse']:.4f}", flush=True)

    print(f"\nDone. {len(results)} rows in {args.out}")


if __name__ == "__main__":
    main()
