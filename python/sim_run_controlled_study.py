"""
Controlled-strength simulation study, single- and two-factor (November 2026), for the
Hoffman2 cluster (cluster/submit_controlled_study.sh) or locally.

Arms, scored by one pipeline (the cluster array runs two_factor, single_factor and
high_pve; arm single was dropped from it on 2026-11-26 and is run only for the
no-regression check):
  single  the existing single-factor controlled datasets
          (sim/data/multi_view_shared_controlled/k.5, generate_controlled_data.R):
          n {100, 200, 500} x P {600, 3000} x c {0.3, 0.6, 1, 1.5, 2, 3, 10}, reps 1-10,
          plus P = 10000 x c {0.3, 1, 3, 10} x all n, reps 1-3 (the replicates that exist).
          This is the rerun of the controlled grid with the new local-inference defaults,
          and the no-regression check: training is unchanged, so on reps 1-3 every
          closed-form and baseline row must reproduce grid_default/scores.csv exactly
          (--compare).
  two_factor  two outcome-relevant factors (docs/viper_shared_extensions_design.md §1): a strong
          (g_1 = 10 sqrt(gamma)) and a weak (g_2 = c sqrt(gamma)) relevant factor, the weak
          one carrying a share omega_2 of the signal; the single-factor (n, P, c) cells
          x omega_2 {0.25, 0.5, 0.75} (162 cells), reps 1-10, rescale_to_target = TRUE.
          Data from R/generate_multifactor_data.R (generated by the task if missing).
  single_factor  the single-factor grid again (the 54 cells of arm single), on data
          whose relevant-factor strength equals its target exactly (rescale_to_target =
          TRUE; generate_multifactor_data.R --single, m = 1, beta = +-1, sigma_y^2 = 0.5;
          the m = 1 design of the missingness and survival studies), reps 1-10. The
          unscaled data of arm single miss the target badly at small c (realised g is
          0-3.9 x target at c = 0.3). Adds step 9 (factor_selection_diag.py): per-factor
          tables and arrays for VIPER, MOFA and PCA15 (with --extra-fits also a permuted-y
          fit and two 80 % subsample fits, diagnostics only), so factor-selection rules
          can be evaluated offline.
  high_pve  one predictive factor as large as the nuisance factors (beta on nuisance
          column 1: dense loadings, PVE ~15 %) and one weak predictive factor
          (g = c sqrt(gamma), own support, rescaled), with 3 nuisance factors (beta = 0);
          the weak factor carries a share omega_2 {0.25, 0.5, 0.75} of the signal, the large
          one 1 - omega_2. The cells of arm two_factor (162), reps 1-10; data from
          generate_multifactor_data.R --highpve (generated by the task); step 9 on. In the
          rows, kappa2_strong is the large predictive factor and kappa2_weak the weak one.

VIPER-Shared uses the package defaults throughout (run_methods.with_defaults, empty
train_config): training as in controlled_grid_default.py (MGP, k = 15, pyro seed = rep,
eta 0.3, avg_param_change stop, SVD init), and local inference of the test scores with
the November 2026 local defaults (training-sd start, 5-epoch warm-up, score-change stop,
scores averaged over the last 150-epoch window). Nothing here sets a setting of its own.

Per dataset:
  1. fit VIPER on the training set; save the param store; stop epoch, fit time, factors
     with > 1 % of training variance, implied-covariance error;
  2. local inference on the test set (train_model_locally), recording every epoch the
     distance of the test score means and sds from the closed-form optimum (d_loc, d_sd)
     and the rule statistics -> local_traj/<cond>_rep<r>.csv;
  3. MOFA2 (15 factors);
  4. misaligned_exact_risk.score_methods: oracle, viper_default (closed-form test scores)
     + _mc, pca5_ols, pca15_ols, mofa, ridge, elastic_net (test outcome MSE, exact risk
     [diagnostic], kappa2, g_hat, E_q[tau]);
  5. viper_local: prediction from the local-inference scores (test MSE, 95 % coverage,
     width, interval score; local epochs and time; final d_loc, d_sd);
  6. viper_scores_ols: OLS (with intercept) of y on VIPER's closed-form training scores;
  7. per relevant factor: kappa2_strong / kappa2_weak / kappa2_rel_mean (in arm single
     the one relevant factor fills all three);
  8. outcome UQ (viper_default closed form, MOFA OLS interval) and implied-covariance
     error for the factor methods.

Runtime: every row's runtime is the time to get that method's predictions from the
training data. For the four VIPER rows that is the training fit (fit_time) plus the
method's own step (local inference [local_time], MC draws, OLS); MOFA's includes its fit.

Output under sim/results/controlled_study/<arm>/: scores/<cond>.csv (one file per cell,
so array tasks never share a file; resumable by rep), models/, mofa/, local_traj/,
factors/<cond>_rep<r>.{csv,npz} (arms single_factor and high_pve).

usage (from python/):
  python sim_run_controlled_study.py --list                    # task id -> (arm, cell)
  OMP_NUM_THREADS=2 python sim_run_controlled_study.py --task-id 7
  OMP_NUM_THREADS=2 python sim_run_controlled_study.py --arm single --cells all --workers 4
  python sim_run_controlled_study.py --compare                 # arm single vs grid_default
"""
import argparse, glob, os, subprocess, sys, time, warnings
import numpy as np, pandas as pd
sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__))))
warnings.filterwarnings("ignore")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_SINGLE = os.path.join(ROOT, "sim", "data", "multi_view_shared_controlled", "k.5")
DATA_B = os.path.join(ROOT, "sim", "data", "multi_view_shared_multifactor", "two_factor")
DATA_ONE = os.path.join(ROOT, "sim", "data", "multi_view_shared_multifactor", "single_factor")
DATA_HIGH = os.path.join(ROOT, "sim", "data", "multi_view_shared_multifactor", "high_pve")
OUT_ROOT = os.path.join(ROOT, "sim", "results", "controlled_study")
GRID_DEFAULT = os.path.join(ROOT, "sim", "results", "integration_shared_controlled", "grid_default", "scores.csv")

N_ARRAY = (100, 200, 500)
K_FIT = 15
SINGLE_MAIN = [(n, P, c) for n in N_ARRAY for P in (600, 3000) for c in (0.3, 0.6, 1, 1.5, 2, 3, 10)]
SINGLE_HIGHDIM = [(n, 10000, c) for n in N_ARRAY for c in (0.3, 1, 3, 10)]
W_ARRAY = (0.25, 0.5, 0.75)
# the same (n, P, c) cells as the single-factor arm, crossed with omega_2
TWO_FACTOR_CELLS = [(n, P, c, w) for n, P, c in SINGLE_MAIN + SINGLE_HIGHDIM for w in W_ARRAY]
REPS_MAIN = tuple(range(1, 11))
REPS_HIGHDIM = (1, 2, 3)
# per-factor diagnostics (step 9): arms that get them. The permuted-y and subsample
# refits (N_PERM, N_SUB) are diagnostics only and off by default (--extra-fits turns on
# 1 + 2): they add ~2.5x the time and a real analysis cannot afford them. Reps 1-3 of
# the P = 10000 and P = 3000 n = 500 cells were run with them (November 2026).
FACTOR_DIAG = {"single_factor": True, "high_pve": True}
N_PERM, N_SUB = 0, 0


def single_tasks():
    """Arm single (the unscaled single-factor data): not in the cluster array (decided
    2026-11-26; arm single_factor covers the same cells with strength on target). Kept
    for the no-regression check against grid_default: --arm single --cells all [--reps 1]
    then --compare."""
    return ([("single", (n, P, c, None), REPS_MAIN) for n, P, c in SINGLE_MAIN]
            + [("single", (n, P, c, None), REPS_HIGHDIM) for n, P, c in SINGLE_HIGHDIM])


def tasks():
    """(arm, cell, reps) for every array task, in task-id order (new arms are appended,
    so the ids of the earlier tasks do not change)."""
    t = [("two_factor", cell, REPS_MAIN) for cell in TWO_FACTOR_CELLS]
    t += [("single_factor", (n, P, c, None), REPS_MAIN) for n, P, c in SINGLE_MAIN + SINGLE_HIGHDIM]
    t += [("high_pve", cell, REPS_MAIN) for cell in TWO_FACTOR_CELLS]
    return t


def cond_name(arm, n, P, c, w):
    return f"n{n}_P{P}_c{c:g}" + ("" if arm in ("single", "single_factor") else f"_w{w:g}")


def load(arm, n, P, c, w, rep):
    from run_methods import load_rds
    cond = cond_name(arm, n, P, c, w)
    if arm == "single":
        root, f = DATA_SINGLE, f"sim_data_controlled_{cond}_rep{rep}.rds"
    elif arm == "single_factor":
        root, f = DATA_ONE, f"sim_data_singlefactor_{cond}_rep{rep}.rds"
    elif arm == "high_pve":
        root, f = DATA_HIGH, f"sim_data_highpve_{cond}_rep{rep}.rds"
    else:
        root, f = DATA_B, f"sim_data_twofactor_{cond}_rep{rep}.rds"
    return load_rds(os.path.join(root, "train", cond, f)), load_rds(os.path.join(root, "test", cond, f))


def generate_b(n, P, c, w, reps, mode=None):
    """Generate the data of one cell (mode None: two-factor, "single", "highpve")."""
    only = f"{n},{P},{c:g}" if mode == "single" else f"{n},{P},{c:g},{w:g}"
    subprocess.run(["Rscript", os.path.join(ROOT, "R", "generate_multifactor_data.R")] + ([f"--{mode}"] if mode else []) +
                   ["--only", only, "--reps", ",".join(map(str, reps))], check=True, stdout=subprocess.DEVNULL)


def uq(y, mu, var, df=None):
    from scipy import stats
    sd = np.sqrt(var); q = stats.t.ppf(0.975, df) if df else stats.norm.ppf(0.975)
    lo, hi = mu - q * sd, mu + q * sd
    return {"cov95": float(np.mean((y >= lo) & (y <= hi))), "width95": float(np.mean(hi - lo)),
            "iscore95": float(np.mean((hi - lo) + 40 * (lo - y) * (y < lo) + 40 * (y - hi) * (y > hi)))}


def record_local(target_m, target_sd):
    """Wrap handler.AveragedParamChange.update (called once per epoch by the rule) to
    record, without changing the run, the distance of the test score means and sds from
    the closed-form optimum, and the rule statistics. Returns (rows, restore)."""
    import handler, pyro, torch
    from constants import Params
    orig = handler.AveragedParamChange.update
    rows = []
    nm, ns = float(torch.linalg.norm(target_m)), float(torch.linalg.norm(target_sd))

    def update(self, store, epoch):
        met = orig(self, store, epoch)
        ps = pyro.get_param_store()
        with torch.no_grad():
            m = ps[Params.loc_Z_pred].detach().double().cpu()
            s = ps[Params.scale_Z_pred].detach().double().cpu()
            row = {"epoch": epoch, "d_loc": float(torch.linalg.norm(m - target_m)) / nm,
                   "d_sd": float(torch.linalg.norm(s - target_sd)) / ns, "rule_met": bool(met)}
        if self.history and self.history[-1][0] == epoch:
            row.update({f"stat_{k}": float(v) for k, v in self.history[-1][1].items()})
        rows.append(row)
        return met

    handler.AveragedParamChange.update = update
    return rows, lambda: setattr(handler.AveragedParamChange, "update", orig)


def one(arm, n, P, c, w, rep):
    """All score rows for one dataset."""
    os.environ.setdefault("OMP_NUM_THREADS", "2")
    import torch, pyro
    torch.set_num_threads(int(os.environ["OMP_NUM_THREADS"]))
    import multiview_shared  # noqa: F401
    from run_methods import process_data, train_model, train_model_locally
    from misaligned_exact_risk import score_methods
    from data_utils import implied_cov_errors
    from viper_predict import load_guide_moments, closed_form_scores
    from controlled_scoring import fit_mofa
    from sklearn.decomposition import PCA
    from constants import Params
    import risk_metrics as rm

    cond = cond_name(arm, n, P, c, w)
    out_dir = os.path.join(OUT_ROOT, arm)
    for sub_dir in ("models", "mofa", "local_traj", "factors"):
        os.makedirs(os.path.join(out_dir, sub_dir), exist_ok=True)
    tr, te = load(arm, n, P, c, w, rep)
    train_sub, test_sub, dp = process_data(tr, te, model_type="shared")
    L = dp["L"]
    Xtr = [x.double() for x in dp["train_X_l_list_clean"]]
    X_te = [x.double() for x in dp["test_X_l_list_clean"]]
    y_tr = dp["train_y_clean"].double().reshape(-1).numpy(); y_te = dp["test_y_clean"].double().reshape(-1).numpy()

    # 1. VIPER training, package defaults (as controlled_grid_default.one)
    stem = os.path.join(out_dir, "models", f"shared_default_{cond}_rep{rep}")
    pyro.clear_param_store(); pyro.set_rng_seed(rep)
    t0 = time.time()
    model, handler_tr, _ = train_model({"k": K_FIT, "dense_model": False}, {}, train_sub, None,
                                       model_type="shared", write=False)
    fit_time = time.time() - t0
    store = pyro.get_param_store()
    store.save(stem + "_paramstore.pth")
    hist = handler_tr.avg_tracker.history
    Zm = store[Params.loc_Z].detach().double(); Sz = store[Params.scale_Z].detach().double()
    Lam = [store[Params.loc_Lambda_l.format(l=l)].detach().double().squeeze() for l in range(L)]
    pve = sum((Zm ** 2).mean(0) * (M ** 2).sum(0) for M in Lam) * Zm.shape[0] / sum(float((x ** 2).sum()) for x in Xtr)
    Sigma_Z = (Zm.T @ Zm + torch.diag((Sz ** 2).sum(0))) / Zm.shape[0]
    extra_viper = {"stop_epoch": model.total_epochs, "fit_time": fit_time,
                   "stat_Lambda_final": hist[-1][1]["Lambda"] if hist else np.nan,
                   "stat_beta_final": hist[-1][1]["beta"] if hist else np.nan,
                   "n_factors_pve1": int((pve > 0.01).sum()),
                   "cov_frob": float(implied_cov_errors(Lam, Sigma_Z, dp).cov_frob.mean())}

    # 2. Local inference of the test scores, package local defaults, recorded per epoch
    mom = load_guide_moments(stem + "_paramstore.pth", L)
    cf_tr = closed_form_scores(mom, Xtr); cf_te = closed_form_scores(mom, X_te)
    target_sd = torch.sqrt(torch.diag(cf_te["cov_z"])).expand_as(cf_te["m_z"])
    pyro.clear_param_store(); pyro.get_param_store().load(stem + "_paramstore.pth")
    torch.manual_seed(rep)
    traj, restore = record_local(cf_te["m_z"], target_sd)
    try:
        model, handler_te, local_state = train_model_locally(model, {}, test_sub, model_type="shared")
    finally:
        restore()
    ps = pyro.get_param_store()
    m_loc = ps[Params.loc_Z_pred].detach().double(); s_loc = ps[Params.scale_Z_pred].detach().double()
    pd.DataFrame(traj).to_csv(os.path.join(out_dir, "local_traj", f"{cond}_rep{rep}.csv"), index=False)
    pyro.clear_param_store()
    mb, s2b = mom["m_beta"], mom["s2_beta"]
    yhat_loc = (m_loc @ mb).numpy()
    var_loc = (mom["E_sigma2_y"] + (s_loc ** 2 * (mb ** 2 + s2b)).sum(1) + (m_loc ** 2 * s2b).sum(1)).numpy()
    local_row = {"method": "viper_local", "outcome_mse": float(np.mean((yhat_loc - y_te) ** 2)),
                 **uq(y_te, yhat_loc, var_loc),
                 "local_epochs": model.local_epochs, "local_time": float(local_state["inference_time"]),
                 "runtime": float(local_state["inference_time"]),
                 "window_mean_epochs": getattr(handler_te, "window_mean_epochs", np.nan),
                 "d_loc": float(torch.linalg.norm(m_loc - cf_te["m_z"]) / torch.linalg.norm(cf_te["m_z"])),
                 "d_sd": float(torch.linalg.norm(s_loc - target_sd) / torch.linalg.norm(target_sd))}

    # 3. MOFA
    mofa_npz = os.path.join(out_dir, "mofa", f"mofa_{cond}_rep{rep}.npz")
    if not os.path.exists(mofa_npz):
        fit_mofa(dp, mofa_npz)

    g_true = np.atleast_1d(tr["g_true"].double().numpy())
    key = {"arm": arm, "n": n, "P_grid": P, "c": c, "rep": rep,
           "omega_weak": np.nan if w is None else w,
           "g_target": float(np.atleast_1d(tr["g_target"].double().numpy())[-1]),
           "g_true": float(g_true[-1]),                      # weak factor (the only one in arm single)
           "g_true_strong": float(g_true[0]) if g_true.size > 1 else np.nan,
           "s": int(np.atleast_1d(tr["s"].numpy())[-1])}

    # 4. Shared scoring of all linear methods
    rows = score_methods(tr, te, key, {"viper_default": stem + "_paramstore.pth"},
                         mofa_npz, with_enet=True, seed=rep)
    base = {k: v for k, v in rows[0].items()
            if k in key or k in ("P", "R_star", "var_y", "g_y", "gamma", "sqrt_gamma")}

    theta = rm.true_params(tr); orc = rm.oracle(theta)
    rel = [k for k in range(theta["beta"].numel()) if float(theta["beta"][k]) != 0]
    k_strong, k_weak = rel[0], rel[-1]
    y_raw = tr["y"].double().reshape(-1); y_mean, y_sd = float(y_raw.mean()), float(y_raw.std())

    # 5. Local-inference prediction
    rows.append({**base, **local_row})

    # 6. VIPER scores + OLS
    t0 = time.time()
    D = np.column_stack([np.ones(n), cf_tr["m_z"].numpy()])
    b, *_ = np.linalg.lstsq(D, y_tr, rcond=None)
    wts = [a_ / b_ for a_, b_ in zip(mom["a_psi"], mom["b_psi"])]
    A_inv = torch.linalg.inv(cf_tr["A_bar"])
    coef_x = [(M_l * w_l[:, None]) @ (A_inv @ torch.as_tensor(b[1:], dtype=torch.float64))
              for M_l, w_l in zip(mom["M"], wts)]
    pred = b[0] + cf_te["m_z"].numpy() @ b[1:]
    rows.append({**base, "method": "viper_scores_ols",
                 **rm.risk_summary(coef_x, dp, y_mean, y_sd, theta, orc, float(b[0])),
                 "outcome_mse": float(np.mean((pred - y_te) ** 2)), "runtime": time.time() - t0})

    # 7. Per-factor kappa2
    Xc = torch.cat(Xtr, 1).numpy(); sizes = [x.shape[1] for x in Xtr]
    split = lambda A: list(torch.split(torch.as_tensor(A, dtype=torch.float64), sizes))
    d = np.load(mofa_npz); W_mofa = [d[f"weights_view{l}"] for l in range(L)]
    loads = {"viper_default": mom["M"], "viper_default_mc": mom["M"], "viper_scores_ols": mom["M"],
             "viper_local": mom["M"], "mofa": [torch.as_tensor(x) for x in W_mofa]}
    pcas = {}
    for kc in (5, 15):
        pcas[kc] = PCA(n_components=kc, random_state=0).fit(Xc)
        loads[f"pca{kc}_ols"] = split(pcas[kc].components_.T)
    loads["oracle"] = [Lm[f] / sd.double().reshape(-1)[:, None] for Lm, f, sd in
                       zip(theta["Lambda"], dp["X_l_list_column_filters"], dp["X_l_sd_list"])]
    k2 = {m: rm.kappa2_hat(rm.raw_loadings(ld, dp), theta)["kappa2_k"] for m, ld in loads.items()}

    # 8. UQ and covariance error
    u_v = uq(y_te, cf_te["yhat"].numpy(), cf_te["pred_var"].numpy())
    Z, Zt = d["Z_train"], d["Z_test"]
    cm, *_ = np.linalg.lstsq(Z, y_tr, rcond=None); kz = Z.shape[1]
    s2 = float(((y_tr - Z @ cm) ** 2).sum() / (n - kz)); Gm = np.linalg.inv(Z.T @ Z)
    u_m = uq(y_te, Zt @ cm, s2 * (1 + np.einsum("ij,jk,ik->i", Zt, Gm, Zt)), n - kz)
    cov = {"mofa": float(implied_cov_errors([torch.as_tensor(x) for x in W_mofa], torch.as_tensor(Z.T @ Z / n), dp).cov_frob.mean())}
    for kc, pca in pcas.items():
        s2n = (Xc.var(0, ddof=1).sum() - pca.explained_variance_.sum()) / (Xc.shape[1] - kc)
        Wp = pca.components_.T * np.sqrt(np.clip(pca.explained_variance_ - s2n, 0, None))
        cov[f"pca{kc}_ols"] = float(implied_cov_errors(split(Wp), None, dp).cov_frob.mean())

    # 9. Per-factor diagnostics for factor-selection rules (factor_selection_diag.py),
    #    with a permuted-y fit and subsample fits; arm single_factor by default
    if FACTOR_DIAG.get(arm, False):
        import factor_selection_diag as fsd
        extra = os.environ.get("CONTROLLED_EXTRA_FITS") == "1"
        fsd.run(tr, dp, train_sub, stem + "_paramstore.pth", m_loc.numpy(), s_loc.numpy(), mofa_npz,
                K_FIT, rep, os.path.join(out_dir, "factors", f"{cond}_rep{rep}"),
                n_perm=1 if extra else N_PERM, n_sub=2 if extra else N_SUB)

    for r in rows:
        m = r["method"]
        if m in k2:
            r.update(kappa2_strong=float(k2[m][k_strong]), kappa2_weak=float(k2[m][k_weak]),
                     kappa2_rel_mean=float(k2[m][rel].mean()))
        if m == "viper_default":
            r.update(extra_viper); r.update(u_v); r["runtime"] = fit_time
        elif m in ("viper_local", "viper_default_mc", "viper_scores_ols"):
            # same VIPER fit: runtime = fit + this method's own step (local inference,
            # MC draws, OLS), so it compares with MOFA's runtime, which includes its fit
            r["stop_epoch"] = extra_viper["stop_epoch"]; r["fit_time"] = fit_time
            r["runtime"] = fit_time + float(r.get("runtime") or 0.0)
            if m == "viper_local":
                r["cov_frob"] = extra_viper["cov_frob"]
        elif m == "mofa":
            r.update(u_m); r["cov_frob"] = cov["mofa"]; r["runtime"] = float(d["runtime"])
        elif m in cov:
            r["cov_frob"] = cov[m]
    return rows


def run_task(arm, cell, reps):
    n, P, c, w = cell
    cond = cond_name(arm, n, P, c, w)
    if arm in ("two_factor", "single_factor", "high_pve"):
        generate_b(n, P, c, w, reps, mode={"two_factor": None, "single_factor": "single", "high_pve": "highpve"}[arm])
    sdir = os.path.join(OUT_ROOT, arm, "scores"); os.makedirs(sdir, exist_ok=True)
    out = os.path.join(sdir, f"{cond}.csv")
    done = set(pd.read_csv(out).rep) if os.path.exists(out) else set()
    for rep in reps:
        if rep in done:
            continue
        t0 = time.time()
        new = pd.DataFrame(one(arm, n, P, c, w, rep))
        if os.path.exists(out):
            new = pd.concat([pd.read_csv(out), new], ignore_index=True)
        new.to_csv(out, index=False)
        print(f"{arm} {cond} rep {rep}: {time.time() - t0:.0f}s", flush=True)


def compare():
    """Arm single vs grid_default/scores.csv on the shared (n, P, c, rep): every
    closed-form and baseline row must be identical (training is unchanged)."""
    files = glob.glob(os.path.join(OUT_ROOT, "single", "scores", "*.csv"))
    new = pd.concat([pd.read_csv(f) for f in files])
    old = pd.read_csv(GRID_DEFAULT)
    keys = ["n", "P_grid", "c", "rep", "method"]
    m = new.merge(old, on=keys, suffixes=("_new", "_old"))
    m["d_mse"] = (m.outcome_mse_new - m.outcome_mse_old).abs()
    m["identical"] = m.d_mse < 1e-12
    print(f"{len(m)} matched rows, {m[['n', 'P_grid', 'c', 'rep']].drop_duplicates().shape[0]} datasets")
    print(m.groupby("method").identical.agg(["sum", "count"]).to_string())
    bad = m[~m.identical]
    if len(bad):
        print("\nnot identical:")
        print(bad[keys + ["outcome_mse_old", "outcome_mse_new", "stop_epoch_old", "stop_epoch_new"]].to_string())
    v = new[new.method.isin(["viper_default", "viper_local"])]
    print("\nviper_default vs viper_local test MSE, per cell (mean over reps):")
    print(v.pivot_table(index=["n", "P_grid", "c"], columns="method", values="outcome_mse").round(4).to_string())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--task-id", type=int, help="1-based task index (SGE_TASK_ID); see --list")
    ap.add_argument("--arm", choices=("single", "two_factor", "single_factor", "high_pve"))
    ap.add_argument("--cells", default=None, help="'all': every cell of --arm")
    ap.add_argument("--reps", nargs="*", type=int, default=None, help="override the replicates")
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--compare", action="store_true")
    ap.add_argument("--extra-fits", action="store_true", help="add the permuted-y and 2 subsample refits to step 9")
    a = ap.parse_args()
    if a.extra_fits:
        os.environ["CONTROLLED_EXTRA_FITS"] = "1"      # read in one(); inherited by the workers
    if a.compare:
        compare(); return
    tl = tasks()
    if a.list:
        for i, (arm, cell, reps) in enumerate(tl, 1):
            print(i, arm, cond_name(arm, *cell), f"reps {reps[0]}-{reps[-1]}")
        print(f"{len(tl)} tasks")
        return
    if a.task_id is not None:
        arm, cell, reps = tl[a.task_id - 1]
        run_task(arm, cell, a.reps or reps); return
    if a.cells != "all" or a.arm is None:
        ap.error("give --task-id N, or --arm and --cells all")
    sel = sorted([t for t in tl + single_tasks() if t[0] == a.arm], key=lambda t: -t[1][0] * t[1][1])   # largest first
    from joblib import Parallel, delayed
    Parallel(n_jobs=a.workers, backend="loky")(delayed(run_task)(arm, cell, a.reps or reps)
                                               for arm, cell, reps in sel)
    print("ALL_DONE", time.ctime(), flush=True)


if __name__ == "__main__":
    main()
